package com.example.littlelemon

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

@Serializable
data class MenuNetwork(
    @SerialName("menu")
    val menu: List<MenuItemNetwork>,
)

typealias MenuNetworkdata = MenuNetwork
typealias MenuNetworkData = MenuNetwork

@Serializable
data class MenuItemNetwork(
    @SerialName("id")
    val id: Int,
    @SerialName("title")
    val title: String,
    @SerialName("description")
    val description: String,
    @SerialName("price")
    val price: String,
    @SerialName("image")
    val image: String,
    @SerialName("category")
    val category: String = "",
)

typealias MenuItemNetworkdata = MenuItemNetwork
typealias MenuItemNetworkData = MenuItemNetwork
